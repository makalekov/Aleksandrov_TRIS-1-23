-- Учебное пересоздание схемы: удаляются только таблицы лабораторной работы.
-- Зависимая таблица удаляется первой, чтобы снять внешние ключи.
DROP TABLE IF EXISTS cable_tickets;
DROP TABLE IF EXISTS network_sites;
DROP TABLE IF EXISTS users;

CREATE TABLE network_sites (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE
);

CREATE TABLE users (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login text NOT NULL UNIQUE,
    role text NOT NULL CHECK (role IN ('Dispatcher', 'Electrician'))
);

CREATE TABLE cable_tickets (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number text NOT NULL UNIQUE,
    title varchar(80) NOT NULL CHECK (char_length(title) BETWEEN 5 AND 80),
    description varchar(500) NOT NULL CHECK (char_length(description) BETWEEN 10 AND 500),
    site_id integer NOT NULL REFERENCES network_sites (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    status text NOT NULL CHECK (status IN ('New', 'InProgress', 'Closed', 'Cancelled')),
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by_user_id integer NOT NULL REFERENCES users (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    assignee_user_id integer NULL REFERENCES users (id) ON UPDATE RESTRICT ON DELETE RESTRICT
);

-- Ускоряет частый фильтр списка заявок по статусу.
CREATE INDEX cable_tickets_status_idx ON cable_tickets (status);

-- Ускоряет фильтрацию и соединение заявок со справочником участков.
CREATE INDEX cable_tickets_site_id_idx ON cable_tickets (site_id);

-- Индексы внешних ключей, создаваемые EF Core по соглашению.
CREATE INDEX "IX_cable_tickets_assignee_user_id" ON cable_tickets (assignee_user_id);
CREATE INDEX "IX_cable_tickets_created_by_user_id" ON cable_tickets (created_by_user_id);
